function buildRoot(s){
  let cursor=0;
  const hosts=s.shots.map(x=>{
    const start=cursor/s.fps,secs=x.durationFrames/s.fps;cursor+=x.durationFrames;
    return `<div id="scene-${x.id}" data-composition-id="scene-${x.id}" data-composition-src="compositions/scene-${x.id}.html" data-track-index="1" data-track-kind="graphics" data-start="${start}" data-duration="${secs}" data-width="1280" data-height="720" data-no-timeline="true"></div>`;
  }).join("\n");
  return `<!doctype html>
<!-- Generated by scripts/build-hyperframes.mjs. Source: content-factory/story.json -->
<html lang="es"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Motion Content Factory / HyperFrames</title>
<style>html,body{margin:0;width:100%;height:100%;background:#0d1117;overflow:hidden}#root{position:relative;width:100%;height:100%;background:#0d1117}</style></head>
<body><main id="root" data-composition-id="main" data-start="0" data-duration="${cursor/s.fps}" data-width="1280" data-height="720" data-no-timeline="true">
${hosts}
</main></body></html>
`;
}

function buildScene(shot,index,count,fps,stylesheet){
  const e=htmlEscape,seconds=shot.durationFrames/fps;
  return `<template>
<style>${stylesheet}</style>
<div id="root" class="shot clip" data-composition-id="scene-${shot.id}" data-width="1280" data-height="720" data-no-timeline="true" style="--accent:${shot.accent};--shot-duration:${seconds}s">
  <div class="grid" data-layout-ignore="true"></div><div class="glow" data-layout-ignore="true"></div>
  <div class="orbit" data-layout-ignore="true"><i></i><i></i><i></i><b></b></div>
  <div class="top"><strong>${e(shot.eyebrow)}</strong><span>0${index+1} / 0${count} &nbsp; ${e(shot.role.toUpperCase())}</span></div>
  <div class="middle"><h1>${e(shot.headline)}</h1><div class="rule"></div><p>${e(shot.detail)}</p></div>
  <div class="bottom"><span>CREATIVE PROOF OF CONCEPT / NO PUBLICAR SIN REVISIÓN</span><span class="tick"></span></div>
  <div class="progress" data-layout-ignore="true"></div>
</div>
</template>
`;
}

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const story = JSON.parse(readFileSync(resolve(rootDir, "content-factory/story.json"), "utf8"));
validateStory(story);
const outputs = new Map();
outputs.set("hyperframes/index.html", buildRoot(story));
story.shots.forEach((shot, index) =>
  outputs.set("hyperframes/compositions/scene-" + shot.id + ".html", buildScene(shot, index, story.shots.length, story.fps, stylesheet))
);
let mismatches = 0;
for (const [relative, expected] of outputs) {
  const path = resolve(rootDir, relative);
  if (process.argv.includes("--check")) {
    let actual = "";
    try { actual = readFileSync(path, "utf8"); } catch { /* Missing. */ }
    if (actual !== expected) { console.error("Out of sync: " + relative); mismatches++; }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, expected);
    console.log("Generated " + relative);
  }
}
if (mismatches) {
  console.error("Run node scripts/build-hyperframes.mjs");
  process.exitCode = 1;
} else if (process.argv.includes("--check")) console.log("All HyperFrames files match storyboard");
